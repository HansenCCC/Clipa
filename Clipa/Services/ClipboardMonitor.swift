import AppKit
import SwiftData
import CryptoKit

/// 轮询 NSPasteboard，捕获并入库剪贴板历史；过滤密码/敏感内容与排除 App。
@MainActor
final class ClipboardMonitor {
    private let storage: StorageService
    private let settings: AppSettings
    private let onChange: () -> Void
    private let pasteboardName: NSPasteboard.Name
    private let readQueue = DispatchQueue(label: "com.hansen.clipa.clipboard-read", qos: .utility)

    private var timer: Timer?
    private var lastChangeCount: Int?
    private var isReading = false
    private var generation = 0
    /// 「我们自己回填」造成的 changeCount：命中则跳过入库，避免选用条目被重排到最前。
    private var suppressedChangeCount: Int?

    // 敏感/瞬态标记类型：命中则不记录（密码管理器等）
    nonisolated private static let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]
    /// CoreDevice 自动同步的图片可声明 TIFF 却永不提供数据；不请求该图片表示，
    /// 以免拖住后续捕获。同步文本仍读取，本机手动复制的图片按正常路径处理。
    nonisolated private static let deviceSyncType = NSPasteboard.PasteboardType("com.apple.coredevice.dtpasteboardd.sync")

    init(storage: StorageService, settings: AppSettings,
         pasteboardName: NSPasteboard.Name = .general, onChange: @escaping () -> Void) {
        self.storage = storage
        self.settings = settings
        self.pasteboardName = pasteboardName
        self.onChange = onChange
    }

    func start() {
        guard timer == nil else { return }
        generation &+= 1
        lastChangeCount = nil
        let timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        poll()
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        generation &+= 1
        suppressedChangeCount = nil
    }

    /// 标记一次由本 App 回填触发的剪贴板变更，下一轮轮询到它时不入库、不重排。
    func suppressNextChange(_ changeCount: Int) {
        suppressedChangeCount = changeCount
    }

    private func poll() {
        // NSPasteboard 数据可能由另一个 App 延迟提供。任何读取（包括 changeCount）
        // 都不放在主线程；只保留一个在途请求，慢来源不会每 0.4 秒堆积后台任务。
        guard timer != nil, !isReading else { return }
        isReading = true
        let generation = generation
        let previousCount = lastChangeCount
        let suppressedCount = suppressedChangeCount
        let name = pasteboardName
        let frontApp = NSWorkspace.shared.frontmostApplication
        let srcID = frontApp?.bundleIdentifier
        let srcName = frontApp?.localizedName
        let excluded = srcID.map { settings.excludedBundleIDs.contains($0) } ?? false

        readQueue.async { [weak self] in
            let result = autoreleasepool {
                let pb = NSPasteboard(name: name)
                let count = pb.changeCount
                guard let previousCount, count != previousCount,
                      count != suppressedCount, !excluded else { return (count, CapturedContent?.none) }
                let content = Self.capture(from: pb)
                // 读取期间发生了下一次复制：丢弃混合/过期快照，下轮读取新版本。
                return (count, pb.changeCount == count ? content : nil)
            }
            DispatchQueue.main.async { [weak self] in
                guard let self else { return }
                self.isReading = false
                guard self.timer != nil, self.generation == generation else { return }
                self.lastChangeCount = result.0
                if let suppressed = self.suppressedChangeCount, result.0 >= suppressed {
                    self.suppressedChangeCount = nil
                    if result.0 == suppressed { return }
                }
                guard let content = result.1 else { return }
                // 等待来源期间用户可能新增排除项，入库前再按最新设置确认一次。
                if let srcID, self.settings.excludedBundleIDs.contains(srcID) { return }
                // SwiftData 模型和设置始终留在主线程，不跨队列传递。
                switch content {
                case .files(let urls): self.insertFiles(urls, srcID: srcID, srcName: srcName)
                case .image(let data): self.insertImage(data, srcID: srcID, srcName: srcName)
                case .text(let plain, let rtf):
                    let detected = self.classifyText(plain)
                    let kind: ClipKind = rtf != nil && detected == .text ? .rtf : detected
                    self.insertText(plain, rtf: kind == .rtf ? rtf : nil, kind: kind,
                                    srcID: srcID, srcName: srcName)
                }
            }
        }
    }

    private enum CapturedContent {
        case files([URL])
        case image(Data)
        case text(String, Data?)
    }

    nonisolated private static func capture(from pb: NSPasteboard) -> CapturedContent? {
        // 1) 敏感/瞬态内容跳过
        let types = pb.types ?? []
        if types.contains(where: { Self.concealedTypes.contains($0) }) {
            return nil
        }

        // 3) 按优先级解析类型：文件 > 图片 > 富文本 > 文本
        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }

        if !types.contains(Self.deviceSyncType), let imgData = imageData(from: pb, types: types) {
            return .image(imgData)
        }

        if types.contains(.rtf), let rtf = pb.data(forType: .rtf),
           let attr = try? NSAttributedString(data: rtf, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil) {
            let plain = attr.string
            guard !plain.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
            return .text(plain, rtf)
        }

        if types.contains(.string), let str = pb.string(forType: .string) {
            let trimmed = str.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }
            return .text(str, nil)
        }
        return nil
    }

    // MARK: - 稳定哈希（跨重启一致，用于去重）

    private func stableHash(_ s: String) -> String { stableHash(Data(s.utf8)) }
    private func stableHash(_ d: Data) -> String {
        SHA256.hash(data: d).prefix(12).map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - 类型判定

    private func classifyText(_ s: String) -> ClipKind {
        if ColorParser.parse(s) != nil { return .color }
        if isLink(s) { return .link }
        if looksLikeCode(s) { return .code }
        return .text
    }

    private func isLink(_ s: String) -> Bool {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(" "), t.count < 2048 else { return false }
        guard let detector = try? NSDataDetector(types: NSTextCheckingResult.CheckingType.link.rawValue) else { return false }
        let range = NSRange(t.startIndex..., in: t)
        if let m = detector.firstMatch(in: t, range: range), m.range == range, m.url != nil {
            return true
        }
        return false
    }

    private func looksLikeCode(_ s: String) -> Bool {
        let codeSignals = ["{", "}", ";", "func ", "def ", "function ", "const ", "let ", "var ", "import ", "class ", "=>", "</", "#include"]
        let hits = codeSignals.filter { s.contains($0) }.count
        let multiline = s.contains("\n")
        return multiline && hits >= 2
    }

    nonisolated private static func imageData(from pb: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> Data? {
        // 只读来源明确提供的格式，禁止把普通文本送进系统图片转换链。
        if types.contains(.png), let png = pb.data(forType: .png) { return png }
        if types.contains(.tiff), let tiff = pb.data(forType: .tiff),
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return png
        }
        // 兜底：任何图像表示（部分 App 复制 PNG 时只给 NSImage 对象）
        if types.contains(where: { NSImage.imageTypes.contains($0.rawValue) }),
           let img = pb.readObjects(forClasses: [NSImage.self], options: nil)?.first as? NSImage,
           let tiff = img.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return png
        }
        return nil
    }

    // MARK: - 入库

    private func insertText(_ text: String, rtf: Data?, kind: ClipKind, srcID: String?, srcName: String?) {
        let preview = String(text.prefix(500))
        let hash = "txt:" + stableHash(text)
        let colorHex = kind == .color ? ColorParser.parse(text)?.label : nil
        let res = storage.insertOrTouch({
            ClipItem(kind: kind, previewText: preview, plainText: text, contentHash: hash,
                     rtfData: rtf, colorHex: colorHex, sourceAppBundleID: srcID, sourceAppName: srcName)
        }, hash: hash)
        afterInsert(isNew: res.isNew)
    }

    private func insertImage(_ data: Data, srcID: String?, srcName: String?) {
        let hash = "img:" + stableHash(data)
        let dims = FileRecognition.dimensions(data: data)
        let transparent = FileRecognition.transparency(data: data)
        let res = storage.insertOrTouch({
            let path = ImageCache.shared.save(data)
            return ClipItem(kind: .image, previewText: "Image", plainText: "", contentHash: hash,
                            imageFilePath: path, imageDimensions: dims, imageTransparent: transparent,
                            sourceAppBundleID: srcID, sourceAppName: srcName)
        }, hash: hash)
        afterInsert(isNew: res.isNew)
    }

    private func insertFiles(_ urls: [URL], srcID: String?, srcName: String?) {
        let names = urls.map { $0.lastPathComponent }.joined(separator: ", ")
        let hash = "file:" + urls.map(\.path).joined(separator: "|")
        // 单个图片文件：生成缩略图，显示为图片预览但仍按文件粘贴
        let isImg = urls.count == 1 && FileRecognition.isImage(urls[0])
        let thumbResult = isImg ? FileRecognition.makeThumbnail(for: urls[0]) : nil
        let dims: String? = isImg ? FileRecognition.dimensions(url: urls[0]) : nil
        let (item, isNew) = storage.insertOrTouch({
            ClipItem(kind: .file, previewText: names, plainText: urls.map(\.path).joined(separator: "\n"),
                     contentHash: hash, thumbnailPath: thumbResult?.name, imageDimensions: dims,
                     imageTransparent: thumbResult?.transparent,
                     fileURLStrings: urls.map(\.absoluteString),
                     sourceAppBundleID: srcID, sourceAppName: srcName)
        }, hash: hash)
        // 回填：旧版本存的图片文件没有缩略图，复制时补上
        if isImg, item.thumbnailPath == nil {
            item.thumbnailPath = thumbResult?.name
            item.imageDimensions = dims
            item.imageTransparent = thumbResult?.transparent
            storage.touch(item)
        }
        // 非图片单文件：用 QuickLook 异步生成内容预览（txt/pdf/psd…）
        if urls.count == 1, !isImg, item.thumbnailPath == nil {
            FileRecognition.generateQLThumbnail(url: urls[0]) { [weak self] name in
                guard let self, let name else { return }
                item.thumbnailPath = name
                self.storage.touch(item)
                self.onChange()
            }
        }
        afterInsert(isNew: isNew)
    }

    private var lastCleanup = Date.distantPast

    private func afterInsert(isNew: Bool) {
        // 节流：最多每 30 秒清理一次（启动/唤出浮层时另有清理）
        if Date().timeIntervalSince(lastCleanup) > 30 {
            lastCleanup = Date()
            storage.cleanup(maxItems: settings.effectiveMaxItems, retentionDays: settings.retentionPeriod.days)
        }
        onChange()
    }
}
